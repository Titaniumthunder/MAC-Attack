"""INT4 version of a run for Tiny-TPU Version 1 (one INT4 PE; the host does the rest, int4.py): the integer flow on
every validation fold, export of the final models for the ZedBoard and the RP2350, and a command-by-command check of
the export against a model of the PE (tiny_tpu_pe.v).

  model/.venv/bin/python modelV3/hardware_int4.py --run modelV3/runs/<folder>
  model/.venv/bin/python modelV3/hardware_int4.py --run modelV3/runs/<folder> --to-zed     also seed 0 -> ZedBoard
  model/.venv/bin/python modelV3/hardware_int4.py --demo --to-zed

--run takes an --int4 run (quantization-aware training: the network the run trained is exported as it is) or an FP32
run (post-training INT4: the same weights rounded to INT4, input statistics and scales from the rows each network
trained on). The FP32 case is the baseline that shows what quantization-aware training buys.
--demo needs no prepared data: post-training INT4 of the frozen model (frozen.json), calibrated and tested on the 64
rows of its INT8 export. It proves the export and the board program, not the model: no validation in it.
--to-zed writes seed 0's header to tinytpu/fpga_zed/sw/modelv3_int4.h (the board program modelv2_int4_test.c).

Writes runs/<folder>/hardware_int4.json, runs/<folder>/val_outputs_int4.npz (evaluate.py scores it) and
modelV3/export/<folder>_int4/seed<k>/ (quant4.json, modelv3_int4.h).
"""
import argparse, json
from pathlib import Path

import numpy as np
import torch

import config as c
import int4 as I
import net as N
import pipeline as F

ZED_HEADER = c.REPO / "tinytpu" / "fpga_zed" / "sw" / "modelv3_int4.h"
OUTPUTS = ["status logit healthy", "status logit developing (trained in version B only)", "status logit faulty",
           "health logit"]


def int4_net(path, cfg, X_calib):
    """The INT4 network of one saved model: as trained (--int4 run) or post-training INT4 of an FP32 model."""
    net = N.load(path, cfg)
    return net if cfg.get("int4") else I.QMLP.from_fp32(net, X_calib)


def first_failing(s, tau, o):
    lv = F.status(s, tau, o[:, :3].argmax(1), o[:, 3])[0]
    return int(np.argmax(lv == 3)) if (lv == 3).any() else None


def pe_check(a0, m):
    """Every neuron of every row through the PE model, command by command: the sums must equal forward_int's."""
    bad, ovf, ins = 0, 0, []
    sums = I.forward_from_a0(a0, m, ins)[0]
    for l, L in enumerate(m["layers"]):
        for r in range(len(a0)):
            for j in range(len(L["W"])):
                s, o = I.pe_neuron(ins[l][r], L["W"][j])
                bad += s != sums[l][r, j]
                ovf |= o
    return {"sums_checked": int(sum(s.size for s in sums)), "sums_differ": int(bad), "overflow": bool(ovf)}


def c_arr(ctype, name, vals, dims=""):
    vals = np.ravel(vals)
    fmt = (lambda v: repr(float(v))) if ctype == "double" else (lambda v: str(int(v)))
    body = ",\n    ".join(", ".join(fmt(v) for v in vals[i:i + 8]) for i in range(0, len(vals), 8))
    return f"static const {ctype} {name}{dims or f'[{len(vals)}]'} = {{\n    {body}\n}};"


def export(folder, m, X, name, hist, source):
    """quant4.json (the model and how to run it) and modelv3_int4.h (the same for the ZedBoard, with 64 test rows)."""
    folder.mkdir(parents=True)                      # never overwrites an export
    a0, sums, out = I.forward_int(X, m)
    sizes, nl = m["sizes"], len(m["layers"])
    q = {"model": name, "hardware": "Tiny-TPU Version 1 (one INT4 PE, CLEAR / MAC / READ, 16-bit sum)", "source": source,
         "sizes": sizes, "inputs": c.INPUTS, "history": hist, "contract": I.__doc__.split("\n\n")[1],
         "outputs": OUTPUTS, "output_rule": "status = argmax of outputs 0..2; health % = 100 * sigmoid(output 3)",
         "mu": m["mu"].tolist(), "sd": m["sd"].tolist(), "s_a": m["s_a"].tolist(), "hmax": m["hmax"], "hshift": m["hshift"],
         "layers": [{"W": L["W"].tolist(), "s_w": L["s_w"].tolist(), "b": L["b"].tolist(), "corr": L["corr"].tolist(),
                     "relu": l + 1 < nl}
                    for l, L in enumerate(m["layers"])],
         "commands_per_inference": int(sum(n * (k + 2) for k, n in zip(sizes, sizes[1:]))),
         "test_rows": {"x": X.tolist(), "a0": a0.tolist(), "sums": [s.tolist() for s in sums], "outputs": out.tolist()}}
    (folder / "quant4.json").write_text(json.dumps(q) + "\n")
    neurons = sum(sizes[1:])
    hdr = [f"/* {name}: modelV3 {'-'.join(map(str, sizes))} in INT4 for Tiny-TPU Version 1, generated by",
           " * modelV3/hardware_int4.py. Do not edit: rerun the script.",
           f" * Source: {source}",
           " * Host flow (int4.py): u = (x - MV4_MU) / MV4_SD; a = q4(u / MV4_SA[0]); per layer l and neuron j the PE sums",
           " * acc = sum a[i] * W[i]; z = (acc + MV4_CORR[j]) * MV4_SA[l] * MV4_SW[j] + MV4_B[j] (double, in this order);",
           " * hidden layers: a = clip(rint(max(z, 0) / MV4_SA[l + 1]), 0, MV4_HMAX) - MV4_HSHIFT; q4(v) = clip(rint(v), -7, 7)",
           " * for the inputs. The last layer's z are the outputs:",
           " * status = argmax of 0..2 (healthy, developing, faulty), health % = 100 * sigmoid(z[3]). */",
           "#ifndef MODELV2_INT4_H", "#define MODELV2_INT4_H", "",
           f"#define MV4_LAYERS  {nl}", f"#define MV4_N_IN    {sizes[0]}", f"#define MV4_N_OUT   {sizes[-1]}",
           f"#define MV4_WIDTH   {max(sizes)}", f"#define MV4_NEURONS {neurons}", f"#define MV4_ROWS    {len(X)}",
           f"#define MV4_COMMANDS {q['commands_per_inference']}   /* PE commands per inference */",
           f"#define MV4_HMAX    {m['hmax']}   /* hidden activations 0..MV4_HMAX, sent to the PE minus MV4_HSHIFT */",
           f"#define MV4_HSHIFT  {m['hshift']}", "",
           c_arr("int", "MV4_SIZES", sizes),
           c_arr("double", "MV4_MU", m["mu"]), c_arr("double", "MV4_SD", m["sd"]), c_arr("double", "MV4_SA", m["s_a"]),
           "/* weights layer by layer, neuron by neuron: W[l][j][i] */",
           c_arr("signed char", "MV4_W", np.concatenate([L["W"].ravel() for L in m["layers"]])),
           "/* per neuron, layer by layer */",
           c_arr("double", "MV4_SW", np.concatenate([L["s_w"] for L in m["layers"]])),
           c_arr("double", "MV4_B", np.concatenate([L["b"] for L in m["layers"]])),
           "/* per neuron: added to the PE sum, HSHIFT * sum of the neuron's weights (0 for layer 0) */",
           c_arr("int", "MV4_CORR", np.concatenate([L["corr"] for L in m["layers"]])),
           'static const char *const MV4_STATUS_NAMES[3] = {"healthy", "developing", "faulty"};', "",
           "/* test rows: network inputs, then what the host flow must give: INT4 inputs, every PE sum, the outputs */",
           c_arr("double", "MV4_X", X, f"[MV4_ROWS][MV4_N_IN]"),
           c_arr("signed char", "MV4_A0", a0, f"[MV4_ROWS][MV4_N_IN]"),
           c_arr("short", "MV4_ACC", np.concatenate(sums, axis=1), f"[MV4_ROWS][MV4_NEURONS]"),
           c_arr("double", "MV4_OUT", out, f"[MV4_ROWS][MV4_N_OUT]"), "", "#endif"]
    (folder / "modelv3_int4.h").write_text("\n".join(hdr) + "\n")
    return folder / "modelv3_int4.h", pe_check(a0, m)


def pick(X, k=64):
    return X[np.linspace(0, len(X) - 1, k).astype(int)]


def demo(to_zed):
    """Post-training INT4 of the frozen model on the 64 rows of its INT8 export: plumbing only, no validation."""
    fz = json.loads(c.FROZEN.read_text())
    run, src = c.RUNS / fz["run"], c.EXPORT / fz["export"]
    cfg = json.loads((run / "config.json").read_text())
    q8 = json.loads((src / "quant.json").read_text())
    xq = np.array([int(t, 16) for t in (src / "vectors_X.hex").read_text().split()]).reshape(-1, len(c.INPUTS))
    X = (np.where(xq > 127, xq - 256, xq) * q8["s_x"]).astype(np.float32)      # the INT8 export's inputs, as real values
    seed = fz["export"].split("seed")[-1]
    fp = N.load(run / "models" / f"final_seed{seed}.pt", cfg)
    net = I.QMLP.from_fp32(fp, X)
    m = I.integer_model(net)
    out = c.EXPORT / f"{fz['run']}_int4_ptq_demo" / f"seed{seed}"
    hdr, pe = export(out, m, X, f"DEMO post-training INT4 of {fz['export']} (64 rows, not validated)",
                     q8["history"], f"post-training INT4 of {fz['export']}, calibrated and tested on its 64 INT8 test rows")
    with torch.no_grad():
        o32 = fp(torch.tensor(X)).numpy()
    c8 = np.array([int(t, 16) for t in (src / "vectors_C.hex").read_text().split()]).reshape(-1, 4)
    c8 = np.where(c8 & (1 << 21), c8 - (1 << 22), c8)
    o8 = (c8 + np.array(q8["last"]["bias_last"])) * np.array(q8["out_scale"])
    o4 = I.forward_int(X, m)[2]
    st = lambda o: o[:, :3].argmax(1)
    h = lambda o: 100 / (1 + np.exp(-o[:, 3]))
    res = {"rows": len(X), "pe_model": pe,
           "status_same_as_fp32": int((st(o4) == st(o32)).sum()), "status_same_as_int8": int((st(o4) == st(o8)).sum()),
           "status_fp32_rows": np.bincount(st(o32), minlength=3).tolist(),
           "health_max_diff_vs_fp32_pct": float(np.abs(h(o4) - h(o32)).max()),
           "health_mean_diff_vs_fp32_pct": float(np.abs(h(o4) - h(o32)).mean())}
    (out / "demo.json").write_text(json.dumps(res, indent=1) + "\n")
    print(json.dumps(res, indent=1), f"\nexport: {out}")
    if to_zed:
        ZED_HEADER.write_text(hdr.read_text())
        print(f"ZedBoard header: {ZED_HEADER}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--run", type=Path)
    g.add_argument("--demo", action="store_true")
    ap.add_argument("--to-zed", action="store_true", help=f"write seed 0's header to {ZED_HEADER}")
    a = ap.parse_args()
    if a.demo:
        return demo(a.to_zed)
    run = a.run.resolve()
    rows = dict(np.load(c.DATA / "rows.npz"))
    cfg = json.loads((run / "config.json").read_text())
    out = c.EXPORT / f"{run.name}_int4"
    if c.stale(cfg, run.name):
        raise SystemExit(1)
    if out.exists():
        raise SystemExit(f"already exported: {out}. Delete that folder to run hardware_int4.py on this run again.")
    kind = "quantization-aware (--int4 run)" if cfg.get("int4") else "post-training INT4 of an FP32 run"
    hist = max(cfg["history"], 1)
    X = F.network_inputs(rows["Z"], rows["s"], rows["rpm"], rows["M"], np.full(len(rows["y"]), hist))
    pad = rows["ds"] == 0
    trained = pad | cfg["data"].endswith("ottawa")   # calibration rows = the rows the network trained on
    val, val_out = [], np.full((len(cfg["seeds"]), len(X), 4), np.nan, np.float32)
    for f in cfg["folds"]:
        held = rows["bearing"] == f["pad"]
        calib = trained & ~np.isin(rows["bearing"], [f["pad"], *f["ott"]])
        for i, seed in enumerate(cfg["seeds"]):
            path = run / "models" / f"{f['pad']}_seed{seed}.pt"
            net = int4_net(path, cfg, X[calib])
            with torch.no_grad():                   # FP32 run: the FP32 network; --int4 run: its fake quantization
                ref = (N.load(path, cfg) if not cfg.get("int4") else net)(torch.tensor(X[held])).numpy()
            m = I.integer_model(net)
            q = I.forward_int(X[held], m)[2]
            every = np.isin(rows["bearing"], [f["pad"], *f["ott"]])    # held-out Ottawa bearings too, as train.py
            val_out[i, every] = I.forward_int(X[every], m)[2]
            s, tau = rows["s"][held], rows["tau"][held][0]
            val.append({"bearing": f["pad"], "seed": seed, "rows": int(held.sum()),
                        "status_decisions_changed": int((ref[:, :3].argmax(1) != q[:, :3].argmax(1)).sum()),
                        "health_max_diff_pct": float(np.abs(100 / (1 + np.exp(-ref[:, 3])) - 100 / (1 + np.exp(-q[:, 3]))).max()),
                        "failing_row_reference": first_failing(s, tau, ref), "failing_row_int4": first_failing(s, tau, q)})
    np.savez(run / "val_outputs_int4.npz", out=val_out, seeds=np.array(cfg["seeds"]))
    final = {}
    try:
        for seed in cfg["seeds"]:
            net = int4_net(run / "models" / f"final_seed{seed}.pt", cfg, X[trained])
            hdr, pe = export(out / f"seed{seed}", I.integer_model(net), pick(X[pad]), f"modelV3 {run.name} seed {seed} INT4",
                             hist, f"{kind}: runs/{run.name}, final_seed{seed}.pt")
            final[f"seed{seed}"] = {"export": f"{out.name}/seed{seed}", "pe_model": pe}
            if a.to_zed and seed == cfg["seeds"][0]:
                ZED_HEADER.write_text(hdr.read_text())
    except BaseException:
        import shutil
        shutil.rmtree(out, ignore_errors=True)       # no half export left behind: a retry would be refused
        raise
    changed, total = sum(v["status_decisions_changed"] for v in val), sum(v["rows"] for v in val)
    res = {"kind": kind, "reference": "FP32 network" if not cfg.get("int4") else "the run's own fake quantization",
           "validation_models": val, "final_models": final,
           "summary": {"status_decisions_changed_pct": 100 * changed / total,
                       "failing_row_identical": all(v["failing_row_reference"] == v["failing_row_int4"] for v in val),
                       "health_max_diff_pct": max(v["health_max_diff_pct"] for v in val),
                       "pe_model_exact": all(v["pe_model"]["sums_differ"] == 0 and not v["pe_model"]["overflow"]
                                             for v in final.values())}}
    (run / "hardware_int4.json").write_text(json.dumps(res, indent=1) + "\n")
    print(json.dumps(res["summary"], indent=1), f"\nexport: {out}" + (f"\nZedBoard header: {ZED_HEADER}" if a.to_zed else ""))


if __name__ == "__main__":
    main()
