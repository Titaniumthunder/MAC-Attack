"""Writes model_v2_data.h for the Version 2 ZedBoard test program.

It holds two models, both from the files the chip test uses (../../chip_v2/test/):
  - our modelV2 INT8 13-32-16-4 (modelV2/quant.json) with its 64 reference rows (vectors_X.hex) and the
    reference raw sums of the last layer (vectors_C.hex)
  - the professor's INT4 8-4-2 (golden_vectors.json): its operands and expected sums per layer

Usage (from this folder):
    python make_model_v2_header.py
    python make_model_v2_header.py --modelv2 DIR --golden FILE
Re-run it after a new export (copy the files into chip_v2/test/ first), then rebuild the SDK application.
"""
import argparse
import json
from pathlib import Path

here = Path(__file__).resolve().parent
test = here.parents[1] / "chip_v2" / "test"
ap = argparse.ArgumentParser()
ap.add_argument("--modelv2", default=test / "modelV2")
ap.add_argument("--golden", default=test / "golden_vectors.json")
ap.add_argument("--out", default=here / "model_v2_data.h")
a = ap.parse_args()

# ------------------------------------------------------------------ modelV2
mdir = Path(a.modelv2)
q = json.loads((mdir / "quant.json").read_text())
sizes = q["sizes"]
layers = q["layers"]
xs = [int(t, 16) for t in (mdir / "vectors_X.hex").read_text().split()]
xs = [v - 256 if v > 127 else v for v in xs]
cs = [int(t, 16) for t in (mdir / "vectors_C.hex").read_text().split()]
cs = [v - (1 << 22) if v & (1 << 21) else v for v in cs]
n_rows = len(xs) // sizes[0]
assert len(xs) == n_rows * sizes[0] and len(cs) == n_rows * sizes[-1]
assert len(layers) == len(sizes) - 1


def arr(vals):
    return "{" + ", ".join(str(v) for v in vals) + "}"


def rows(mat, indent="    "):
    return "{\n" + ",\n".join(indent + arr(r) for r in mat) + "\n}"


out = []
out.append("/* model_v2_data.h: generated by make_model_v2_header.py, do not edit. */")
out.append("#ifndef MODEL_V2_DATA_H")
out.append("#define MODEL_V2_DATA_H")
out.append("#include <stdint.h>")
out.append("")
out.append(f"/* modelV2: {q['model']} */")
out.append(f"#define M_N_LAYERS {len(layers)}")
out.append(f"#define M_N_ROWS {n_rows}")
out.append(f"#define M_N_IN {sizes[0]}")
out.append(f"#define M_N_OUT {sizes[-1]}")
out.append(f"#define M_MAX_N {max(sizes)}")
out.append(f"static const int M_SIZES[{len(sizes)}] = {arr(sizes)};")
out.append("")
for li, L in enumerate(layers):
    K, N = sizes[li], sizes[li + 1]
    W = L["W"]                                       # K x N
    assert len(W) == K and all(len(r) == N for r in W)
    cols = [[W[k][j] for k in range(K)] for j in range(N)]
    for j in range(N):
        assert -(1 << 23) <= L["bias"][j] < (1 << 23) and 0 <= L["m0"][j] < 65536 and 0 <= L["shift"][j] <= 47
    out.append(f"/* layer {li}: {K} -> {N}, ReLU {'on' if L['relu'] else 'off'}; weights neuron by neuron */")
    out.append(f"static const int8_t M_L{li}_W[{N}][{K}] = {rows(cols)};")
    out.append(f"static const int32_t M_L{li}_BIAS[{N}] = {arr(L['bias'])};")
    out.append(f"static const uint16_t M_L{li}_M0[{N}] = {arr(L['m0'])};")
    out.append(f"static const uint8_t M_L{li}_SHIFT[{N}] = {arr(L['shift'])};")
    out.append("")
out.append("typedef struct {")
out.append("    int k, n, relu;")
out.append("    const int8_t *w;            /* n x k, neuron-major */")
out.append("    const int32_t *bias;")
out.append("    const uint16_t *m0;")
out.append("    const uint8_t *shift;")
out.append("} tpu_layer_t;")
out.append(f"static const tpu_layer_t M_LAYERS[{len(layers)}] = {{")
for li, L in enumerate(layers):
    out.append(f"    {{{sizes[li]}, {sizes[li + 1]}, {1 if L['relu'] else 0}, &M_L{li}_W[0][0], M_L{li}_BIAS, "
               f"M_L{li}_M0, M_L{li}_SHIFT}},")
out.append("};")
out.append("")
out.append("/* reference rows: INT8 inputs and the last layer's raw sums (vectors_X.hex, vectors_C.hex) */")
out.append(f"static const int8_t M_X[{n_rows}][{sizes[0]}] = "
           f"{rows([xs[r * sizes[0]:(r + 1) * sizes[0]] for r in range(n_rows)])};")
out.append(f"static const int32_t M_C[{n_rows}][{sizes[-1]}] = "
           f"{rows([cs[r * sizes[-1]:(r + 1) * sizes[-1]] for r in range(n_rows)])};")
out.append("")
out.append("/* reading the output: real[j] = (C[j] + bias_last[j]) * out_scale[j]; status = argmax of 0..2;")
out.append("   health % = 100 * sigmoid(real[3]) */")
out.append(f"static const int32_t M_BIAS_LAST[{sizes[-1]}] = {arr(q['last']['bias_last'])};")
out.append(f"static const double M_OUT_SCALE[{sizes[-1]}] = {arr(repr(float(v)) for v in q['out_scale'])};")
names = [o.split()[2] for o in q["outputs"] if o.startswith("status logit")]
out.append(f"#define M_N_STATUS {len(names)}")
out.append(f"static const char *const M_STATUS_NAMES[{len(names)}] = {{" + ", ".join(f'"{n}"' for n in names) + "};")
out.append("")

# ------------------------------------------------------------------ the professor's INT4 model
vec = json.loads(Path(a.golden).read_text())
per_vec = []                                          # [vector][layer] -> (a, [w per neuron], [expected])
for v in vec:
    neurons, cur = [], None
    for op in v["commands"]:
        if op["op"] == "CLEAR":
            cur = {"layer": op["layer"], "a": [], "w": []}
        elif op["op"] == "MAC":
            cur["a"].append(op["a"])
            cur["w"].append(op["w"])
        else:
            cur["expected"] = op["expected_acc"]
            neurons.append(cur)
    lay = []
    for layer in sorted({n["layer"] for n in neurons}):
        ns = [n for n in neurons if n["layer"] == layer]
        assert all(n["a"] == ns[0]["a"] for n in ns), "one input vector per layer"
        lay.append((ns[0]["a"], [n["w"] for n in ns], [n["expected"] for n in ns]))
    per_vec.append(lay)
assert len(per_vec[0]) == 2
n_in, n_hid, n_out = len(per_vec[0][0][0]), len(per_vec[0][0][1]), len(per_vec[0][1][1])
W0, W1 = per_vec[0][0][1], per_vec[0][1][1]
assert all(p[0][1] == W0 and p[1][1] == W1 for p in per_vec), "same weights for every vector"
out.append("/* the professor's INT4 model (golden_vectors.json), run in bypass mode: raw sums out */")
out.append(f"#define P_N_VEC {len(per_vec)}")
out.append(f"#define P_N_IN {n_in}")
out.append(f"#define P_N_HID {n_hid}")
out.append(f"#define P_N_OUT {n_out}")
out.append(f"static const int8_t P_W0[{n_hid}][{n_in}] = {rows(W0)};")
out.append(f"static const int8_t P_W1[{n_out}][{n_hid}] = {rows(W1)};")
out.append(f"static const int8_t P_A0[{len(per_vec)}][{n_in}] = {rows([p[0][0] for p in per_vec])};")
out.append(f"static const int8_t P_A1[{len(per_vec)}][{n_hid}] = {rows([p[1][0] for p in per_vec])};")
out.append(f"static const int32_t P_S0[{len(per_vec)}][{n_hid}] = {rows([p[0][2] for p in per_vec])};")
out.append(f"static const int32_t P_S1[{len(per_vec)}][{n_out}] = {rows([p[1][2] for p in per_vec])};")
out.append("")
out.append("#endif")

Path(a.out).write_text("\n".join(out) + "\n")
print(f"wrote {a.out}: modelV2 {'-'.join(map(str, sizes))} with {n_rows} rows, "
      f"professor's INT4 {n_in}-{n_hid}-{n_out} with {len(per_vec)} vectors")
