"""Writes model_data.h for the ZedBoard test program from the model export.

Usage (from this folder):
    python make_model_header.py                       # uses ../../chip/test/{int4_package,golden_vectors}.json
    python make_model_header.py --package P --vectors V

Re-run it after every training run (copy the new int4_package.json and golden_vectors.json into
chip/test/ first), then rebuild the SDK application.
"""
import argparse
import json
from pathlib import Path

here = Path(__file__).resolve().parent
ap = argparse.ArgumentParser()
ap.add_argument("--package", default=here.parents[1] / "chip" / "test" / "int4_package.json")
ap.add_argument("--vectors", default=here.parents[1] / "chip" / "test" / "golden_vectors.json")
ap.add_argument("--out", default=here / "model_data.h")
a = ap.parse_args()

pkg = json.loads(Path(a.package).read_text())
vec = json.loads(Path(a.vectors).read_text())
n_in, n_hid, n_out = pkg["model"]
W0, W1 = pkg["weights"]
B0, B1 = pkg["biases"]
assert len(W0) == n_hid and len(W0[0]) == n_in and len(W1) == n_out and len(W1[0]) == n_hid


def arr(vals, fmt="{}"):
    return "{" + ", ".join(fmt.format(v) for v in vals) + "}"


def d(v):
    return repr(float(v))          # shortest exact round-trip form of the double


ops = []                            # the full CLEAR/MAC/READ stream, for the replay test
for v in vec:
    for op in v["commands"]:
        if op["op"] == "CLEAR":
            ops.append("{1, 0, 0, 0}")
        elif op["op"] == "MAC":
            ops.append(f"{{2, {op['a']}, {op['w']}, 0}}")
        else:
            ops.append(f"{{3, 0, 0, {op['expected_acc']}}}")

lines = [
    "/* Generated by make_model_header.py from int4_package.json and golden_vectors.json. Do not edit. */",
    "#ifndef MODEL_DATA_H",
    "#define MODEL_DATA_H",
    "",
    f"#define N_IN  {n_in}",
    f"#define N_HID {n_hid}",
    f"#define N_OUT {n_out}",
    f"#define N_VEC {len(vec)}",
    f"#define N_OPS {len(ops)}",
    "",
    f"static const double SCALE_A[2] = {arr(pkg['activation_scales'], '{!r}')};   /* activation scale per layer */",
    f"static const double SCALE_W[2] = {arr(pkg['weight_scales'], '{!r}')};   /* weight scale per layer */",
    f"static const signed char W0[N_HID][N_IN] = {arr([arr(r) for r in W0])};",
    f"static const signed char W1[N_OUT][N_HID] = {arr([arr(r) for r in W1])};",
    f"static const double B0[N_HID] = {arr([d(b) for b in B0])};",
    f"static const double B1[N_OUT] = {arr([d(b) for b in B1])};",
    f"static const char *const LABELS[N_OUT] = {arr(pkg['labels'], chr(34) + '{}' + chr(34))};",
    "",
    "/* Test inputs (normalized features) and what the Python reference got for each */",
    f"static const double X[N_VEC][N_IN] = {arr([arr([d(x) for x in v['input_features_normalized']]) for v in vec])};",
    f"static const double EXPECTED_LOGITS[N_VEC][N_OUT] = {arr([arr([d(x) for x in v['expected_logits']]) for v in vec])};",
    f"static const int EXPECTED_CLASS[N_VEC] = {arr([v['expected_class'] for v in vec])};",
    "",
    "/* The same inferences as a raw command stream: {op (1 CLEAR, 2 MAC, 3 READ), a, w, expected acc} */",
    "typedef struct { signed char op, a, w; short expected; } tpu_op_t;",
    "static const tpu_op_t OPS[N_OPS] = {",
    *["    " + ", ".join(ops[i:i + 8]) + "," for i in range(0, len(ops), 8)],
    "};",
    "",
    "#endif",
]
Path(a.out).write_text("\n".join(lines) + "\n")
print(f"Wrote {a.out}: {len(vec)} inferences, {len(ops)} commands, model {n_in}-{n_hid}-{n_out}")
