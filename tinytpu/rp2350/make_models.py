"""Writes the model files the RP2350 loads (run on the PC, from this folder):  python make_models.py

  model_v2.py  modelV2 13-32-16-4 INT8 for Version 2: per layer the weights (neuron by neuron), bias,
               m0, shift and ReLU flag; the 64 reference rows (vectors_X.hex) and their last-layer raw sums
               (vectors_C.hex); how to read the outputs (bias_last, out_scale, status names)
  model_v1.py  the professor's INT4 8-4-2 for Version 1: weights, scales, float biases, normalization, and
               his 12 golden inputs with their expected sums, logits and classes

Sources: ../chip_v2/test/modelV2/ and ../chip/test/{int4_package.json, golden_vectors.json}. After a new
export, copy the new files there, rerun this, the chip tests and sim/run.py, then copy the .py files to the
board again.
"""
import json
from pathlib import Path

here = Path(__file__).resolve().parent
v2dir = here.parent / "chip_v2" / "test" / "modelV2"
v1dir = here.parent / "chip" / "test"


def tup(vals):
    vals = list(vals)
    return "(" + ", ".join(repr(v) for v in vals) + ("," if len(vals) == 1 else "") + ")"


# ------------------------------------------------------------------ Version 2: modelV2
q = json.loads((v2dir / "quant.json").read_text())
sizes = q["sizes"]
xs = [int(t, 16) for t in (v2dir / "vectors_X.hex").read_text().split()]
cs = [int(t, 16) for t in (v2dir / "vectors_C.hex").read_text().split()]
cs = [v - (1 << 22) if v & (1 << 21) else v for v in cs]
rows = len(xs) // sizes[0]

out = ["# model_v2.py: generated by make_models.py from chip_v2/test/modelV2 -- do not edit.",
       f"# {q['model']}",
       "# A layer: (k inputs, n outputs, ReLU, weights n*k signed bytes neuron by neuron, bias, m0, shift)",
       f"SIZES = {tup(sizes)}",
       "LAYERS = ("]
for li, L in enumerate(q["layers"]):
    k, n = sizes[li], sizes[li + 1]
    w = bytes((L["W"][kk][j] & 0xFF) for j in range(n) for kk in range(k))
    assert all(0 <= s <= 47 for s in L["shift"]) and all(0 <= m < 65536 for m in L["m0"])
    assert all(-(1 << 23) <= b < (1 << 23) for b in L["bias"])
    out.append(f"    ({k}, {n}, {1 if L['relu'] else 0}, {w!r},")
    out.append(f"     {tup(L['bias'])},")
    out.append(f"     {tup(L['m0'])},")
    out.append(f"     {bytes(L['shift'])!r}),")
out.append(")")
out.append(f"N_ROWS = {rows}")
out.append("X = (")
for r in range(rows):
    out.append(f"    {bytes(v for v in xs[r * sizes[0]:(r + 1) * sizes[0]])!r},")
out.append(")")
out.append("C = (")
for r in range(rows):
    out.append(f"    {tup(cs[r * sizes[-1]:(r + 1) * sizes[-1]])},")
out.append(")")
out.append("# reading the outputs: real[j] = (C[j] + BIAS_LAST[j]) * OUT_SCALE[j]; status = argmax of the first")
out.append("# three; health % = 100 * sigmoid(real[3])")
out.append(f"BIAS_LAST = {tup(q['last']['bias_last'])}")
out.append(f"OUT_SCALE = {tup(float(v) for v in q['out_scale'])}")
out.append(f"STATUS_NAMES = {tup(o.split()[2] for o in q['outputs'] if o.startswith('status logit'))}")
(here / "model_v2.py").write_text("\n".join(out) + "\n")

# ------------------------------------------------------------------ Version 1: the professor's model
p = json.loads((v1dir / "int4_package.json").read_text())
g = json.loads((v1dir / "golden_vectors.json").read_text())
n_in, n_hid, n_out = p["model"]
sums = [[c["expected_acc"] for c in v["commands"] if c["op"] == "READ"] for v in g]
assert all(len(s) == n_hid + n_out for s in sums)
out = ["# model_v1.py: generated by make_models.py from chip/test (the professor's kit) -- do not edit.",
       f"# INT4 {n_in}-{n_hid}-{n_out}; {p['quantization']}; {p['postprocess']}",
       f"N_IN, N_HID, N_OUT = {n_in}, {n_hid}, {n_out}",
       f"SCALE_A = {tup(p['activation_scales'])}",
       f"SCALE_W = {tup(p['weight_scales'])}",
       f"W0 = {tup(tup(r) for r in p['weights'][0])}".replace("'", ""),
       f"W1 = {tup(tup(r) for r in p['weights'][1])}".replace("'", ""),
       f"B0 = {tup(p['biases'][0])}",
       f"B1 = {tup(p['biases'][1])}",
       f"LABELS = {tup(p['labels'])}",
       f"FEATURES = {tup(p['input_features'])}",
       f"MEAN = {tup(p['normalization']['mean'])}",
       f"STD = {tup(p['normalization']['std'])}",
       "# the professor's golden inputs (normalized) and what his Python reference gives for them",
       f"TEST_X = {tup(tup(v['input_features_normalized']) for v in g)}".replace("'", ""),
       f"TEST_SUMS = {tup(tup(s) for s in sums)}".replace("'", ""),
       f"TEST_LOGITS = {tup(tup(v['expected_logits']) for v in g)}".replace("'", ""),
       f"TEST_CLASS = {tup(v['expected_class'] for v in g)}"]
(here / "model_v1.py").write_text("\n".join(out) + "\n")
print(f"model_v2.py: {'-'.join(map(str, sizes))}, {rows} rows;  model_v1.py: {n_in}-{n_hid}-{n_out}, {len(g)} golden vectors")
