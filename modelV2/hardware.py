"""INT8 version of a run: FP32 vs INT8 on every validation fold, export of the final models for the chip, and the
RTL bit-exact check (Icarus Verilog, tb_mlp.sv), as run 3 did.

  model/.venv/bin/python modelV2/hardware.py --run modelV2/runs/<folder>

Writes runs/<folder>/hardware.json and modelV2/export/<folder>/seed<k>/ (W, Bias, Scl .hex, model.h, quant.json, vectors).
"""
import argparse, json, shutil, tempfile
from pathlib import Path

import numpy as np
import torch

import config as c
import net as N
import pipeline as F
import mtl_model as mm                             # model/: int8_forward = bit-exact chip model + accumulator check
import rtl_check                                   # model/
from export import build, c_array                  # model/
from mac import golden_mlp, write_hex              # mac_attack_accel_MLP/ (path added by mtl_model)


def load(path):
    net = N.mlp()
    net.load_state_dict(torch.load(path, weights_only=True))
    return net.eval()


def quantize(net, X_calib):
    """INT8 layers from the FP32 net. Weights below 1e-6 of their layer's largest are zeroed first: weight decay
    shrinks dead neurons' weights towards 0 and the INT32 biases then overflow (seen in run 3)."""
    with torch.no_grad():
        for m in net:
            if isinstance(m, torch.nn.Linear):
                m.weight[m.weight.abs() < 1e-6 * m.weight.abs().max()] = 0.0
    layers, scales = build(net, X_calib, c.S_X)
    assert all(np.abs(L["bias"]).max() < 2 ** 31 for L in layers), "INT32 bias out of range"
    return layers, scales


def int8(X, layers, last):
    """Chip + host: the 4 real-valued outputs per row."""
    return mm.int8_forward(X, layers, [last], c.S_X)[2]


def load_export(folder):
    q = json.loads((Path(folder) / "quant.json").read_text())
    layers = [{k: (np.array(v) if k != "relu" else v) for k, v in L.items()} for L in q["layers"]]
    return layers, {k: np.array(v) for k, v in q["last"].items()}, q


def export(folder, layers, scales, Xq, name, hist):
    folder.mkdir(parents=True)                      # never overwrites an export
    for l, L in enumerate(layers):
        write_hex(folder / f"W{l}.hex", L["W"], 8)
        write_hex(folder / f"Bias{l}.hex", L["bias"], 32)
        write_hex(folder / f"Scl{l}.hex", (np.asarray(L["shift"]) << 16) | np.asarray(L["m0"]), 24)
    last = scales[-1]
    out_scale = (last["s_in"] * np.asarray(last["s_w"])).tolist()
    floor = json.loads((c.DATA / "summary.json").read_text())["sigma_floor"]
    quant = {"model": name, "sizes": [len(c.INPUTS), *c.HIDDEN, 4], "inputs": c.INPUTS, "s_x": c.S_X,
             "history": hist,                       # rows of history the m4_* inputs were trained with (live.py uses it)
             "input_rule": "q = clip(round_half_away(slog(v) / s_x), -127, 127), slog(v) = sign(v) * ln(1 + min(|v|, 1e4))",
             "outputs": ["status logit healthy", "status logit developing (trained in version B only)", "status logit faulty", "health logit"],
             "output_rule": "real[j] = (C[j] + bias_last[j]) * out_scale[j]; status = argmax of 0..2; health % = 100 * sigmoid(real[3])",
             "sigma_floor": floor, "out_scale": out_scale,
             "layers": [{"W": L["W"].tolist(), "bias": L["bias"].tolist(), "m0": np.asarray(L["m0"]).tolist(),
                         "shift": np.asarray(L["shift"]).tolist(), "relu": L["relu"]} for L in layers],
             "last": {"s_in": last["s_in"], "s_w": np.asarray(last["s_w"]).tolist(), "bias_last": last["bias_last"].tolist()}}
    (folder / "quant.json").write_text(json.dumps(quant) + "\n")
    hdr = [f"/* {name}: {' -> '.join(map(str, quant['sizes']))}, generated by modelV2/hardware.py.",
           " * INT8 weights K x N row-major, INT32 biases, per-channel (m0, shift). The chip returns the raw sums C of the",
           f" * last layer; the host computes {quant['output_rule']}. */", "#pragma once", "#include <stdint.h>",
           f"#define MG2_S_X {c.S_X!r}f",
           c_array("int32_t", "MG2_BIAS_LAST", last["bias_last"]),
           "static const float MG2_OUT_SCALE[4] = {" + ", ".join(f"{v!r}f" for v in out_scale) + "};"]
    for l, L in enumerate(layers):
        hdr += [c_array("int8_t", f"MG2_W{l}", L["W"]), c_array("int32_t", f"MG2_B{l}", L["bias"])]
        if L["relu"]:
            hdr += [c_array("int32_t", f"MG2_M0_{l}", L["m0"]), c_array("int8_t", f"MG2_SHIFT_{l}", L["shift"])]
    (folder / "model.h").write_text("\n".join(hdr) + "\n")
    sel = Xq[np.linspace(0, len(Xq) - 1, 64).astype(int)]
    write_hex(folder / "vectors_X.hex", sel, 8)
    write_hex(folder / "vectors_C.hex", golden_mlp(sel, layers)[0], 22)


def rtl(sim, work, layers, Xq):
    """Every C value and cycle count of the RTL against the golden model: 4 batches of 64 rows and 5 single rows."""
    pick = Xq[np.linspace(0, len(Xq) - 1, 256).astype(int)]
    ok64, _, cyc64, _ = rtl_check.run(sim, work, layers, [pick[i:i + 64] for i in range(0, 256, 64)], 0)
    ok1, _, cyc1, _ = rtl_check.run(sim, work, layers, [pick[[i]] for i in range(0, 256, 52)], 0)
    return {"pass": bool(ok64 and ok1), "cycles_M64": cyc64, "cycles_M1": cyc1}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run", type=Path, required=True)
    run = ap.parse_args().run.resolve()
    rows = dict(np.load(c.DATA / "rows.npz"))
    cfg = json.loads((run / "config.json").read_text())
    out = c.EXPORT / run.name
    if c.stale(cfg, run.name):
        raise SystemExit(1)
    if out.exists():
        raise SystemExit(f"already exported: {out}. Delete that folder to run hardware.py on this run again.")
    hist = max(cfg["history"], 1)
    X = F.network_inputs(rows["Z"], rows["s"], rows["rpm"], rows["M"], np.full(len(rows["y"]), hist))
    pad = rows["ds"] == 0
    trained = pad | cfg["data"].endswith("ottawa")   # calibration rows = the rows the network trained on
    val = []
    for f in cfg["folds"]:
        held = rows["bearing"] == f["pad"]
        for seed in cfg["seeds"]:
            net = load(run / "models" / f"{f['pad']}_seed{seed}.pt")
            with torch.no_grad():
                fp = net(torch.tensor(X[held])).numpy()
            layers, scales = quantize(net, X[trained & ~np.isin(rows["bearing"], [f["pad"], *f["ott"]])])
            q = int8(X[held], layers, scales[-1])
            s, tau = rows["s"][held], rows["tau"][held][0]
            first = [int(np.argmax(lv == 3)) if (lv == 3).any() else None
                     for lv in (F.status(s, tau, o[:, :3].argmax(1), o[:, 3])[0] for o in (fp, q))]
            val.append({"bearing": f["pad"], "seed": seed, "rows": int(held.sum()),
                        "status_decisions_changed": int((fp[:, :3].argmax(1) != q[:, :3].argmax(1)).sum()),
                        "health_max_diff_pct": float(np.abs(100 / (1 + np.exp(-fp[:, 3])) - 100 / (1 + np.exp(-q[:, 3]))).max()),
                        "failing_row_fp32": first[0], "failing_row_int8": first[1]})
    root = Path(tempfile.mkdtemp(prefix="modelV2_rtl_"))
    try:
        sim = rtl_check.TempSimulator(root, "icarus")
        work = sim.build("tb_mlp", rtl_check.PARAMS)
        final = {}
        for seed in cfg["seeds"]:
            layers, scales = quantize(load(run / "models" / f"final_seed{seed}.pt"), X[trained])
            Xq = mm.int8_forward(X[pad], layers, scales, c.S_X)[0]
            folder = c.EXPORT / run.name / f"seed{seed}"
            export(folder, layers, scales, Xq, f"modelV2 {run.name} seed {seed}", hist)
            final[f"seed{seed}"] = {"export": f"{run.name}/seed{seed}", "rtl": rtl(sim, work, layers, Xq)}
    except BaseException:
        shutil.rmtree(out, ignore_errors=True)       # no half export left behind: a retry would be refused
        raise
    finally:
        shutil.rmtree(root, ignore_errors=True)
    changed, total = sum(v["status_decisions_changed"] for v in val), sum(v["rows"] for v in val)
    res = {"validation_models": val, "final_models": final,
           "summary": {"status_decisions_changed_pct": 100 * changed / total,
                       "failing_row_identical": all(v["failing_row_fp32"] == v["failing_row_int8"] for v in val),
                       "health_max_diff_pct": max(v["health_max_diff_pct"] for v in val),
                       "rtl_bit_exact": all(v["rtl"]["pass"] for v in final.values())}}
    (run / "hardware.json").write_text(json.dumps(res, indent=1) + "\n")
    print(json.dumps(res["summary"], indent=1), f"\nexport: {c.EXPORT / run.name}")


if __name__ == "__main__":
    main()
